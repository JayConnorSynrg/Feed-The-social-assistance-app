export function formsT(locale: Locale, key: FormsKey): string {
  return translate(formsMessages, locale, key)
}

/** "Est. 1 h 30 min" — a template's estimated time, in the locale's digits. */
export function estimatedTimeText(minutes: number, locale: Locale): string {
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  if (h === 0) return formatMessage(formsT(locale, 'estMinutes'), { m: formatCount(m, locale) })
  if (m === 0) return formatMessage(formsT(locale, 'estHours'), { h: formatCount(h, locale) })
  return formatMessage(formsT(locale, 'estHoursMinutes'), { h: formatCount(h, locale), m: formatCount(m, locale) })
}

/** The hub's category chip ('benefits' is the hub's own; the others are resource categories, read
 *  from their one source). The stored or derived value never changes. */
export function formsCategoryLabel(category: string, locale: Locale): string {
  return category === 'benefits' ? formsT(locale, 'catBenefits') : resourceCategoryLabel(category, locale)
}

/** A government form's category chip: 'veteran' and 'disability' are this list's own words. */
export function govCategoryLabel(category: string, locale: Locale): string {
  if (category === 'veteran') return formsT(locale, 'catVeteran')
  if (category === 'disability') return formsT(locale, 'catDisability')
  return resourceCategoryLabel(category, locale)
}

