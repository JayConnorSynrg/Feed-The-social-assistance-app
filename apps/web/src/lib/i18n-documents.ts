export function documentsT(locale: Locale, key: DocumentsKey): string {
  return translate(documentsMessages, locale, key)
}

/** The folder values a document row stores (and 'all', the panel's own "every folder"). */
type DocumentFolder = 'all' | 'id' | 'income' | 'residence' | 'medical' | 'forms' | 'other'

const FOLDER_KEYS: Record<DocumentFolder, DocumentsKey> = {
  all: 'catAll',
  id: 'catId',
  income: 'catIncome',
  residence: 'catResidence',
  medical: 'catMedical',
  forms: 'catForms',
  other: 'catOther',
}

/** A folder's label in the viewer's language; the stored value itself never changes. An unknown
 *  value reads as Other. */
export function documentCategoryLabel(category: string, locale: Locale): string {
  const key = Object.prototype.hasOwnProperty.call(FOLDER_KEYS, category) ? FOLDER_KEYS[category as DocumentFolder] : 'catOther'
  return documentsT(locale, key)
}

/** "1.5 MB" in the locale's digits and decimal mark. */
export function documentSize(bytes: number, locale: Locale): string {
  if (bytes < 1024) return formatMessage(documentsT(locale, 'sizeBytes'), { n: formatCount(bytes, locale) })
  if (bytes < 1024 * 1024) return formatMessage(documentsT(locale, 'sizeKb'), { n: formatFixed(bytes / 1024, 1, locale) })
  return formatMessage(documentsT(locale, 'sizeMb'), { n: formatFixed(bytes / (1024 * 1024), 1, locale) })
}

/** When a document was added: Today, Yesterday, "3 days ago" for a week, then the date. */
export function documentDate(date: Date, locale: Locale, now: number = Date.now(), tz: string = browserTimeZone()): string {
  const days = Math.floor((now - date.getTime()) / (1000 * 60 * 60 * 24))
  if (days <= 0) return documentsT(locale, 'today')
  if (days === 1) return documentsT(locale, 'yesterday')
  if (days < 7) return relativePast(days, 'day', locale) ?? formatMessage(documentsT(locale, 'daysAgo'), { n: formatCount(days, locale) })
  return formatDate(date.toISOString(), locale, tz)
}

