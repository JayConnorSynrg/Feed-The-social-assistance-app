/** The fixed English sentences lib/hooks write (hooks/use-encrypted-upload.ts, lib/vault.ts,
 *  contexts/vault-context.tsx), read as codes. */
const DOCUMENT_SENTENCES: Record<string, DocumentsKey> = {
  'Document timed out — please check your connection and retry.': 'docTimedOut',
  'Upload timed out — please check your connection and retry.': 'uploadTimedOut',
}
const VAULT_SENTENCES: Record<string, DocumentsKey> = {
  'Incorrect password': 'incorrectPassword',
  'Vault operation timed out. Please check your connection and try again.': 'vaultTimedOut',
}

function sentenceText(error: string, locale: Locale, own: Record<string, DocumentsKey>, fallback: DocumentsKey): string {
  if (Object.prototype.hasOwnProperty.call(own, error)) return documentsT(locale, own[error])
  if (Object.prototype.hasOwnProperty.call(FRIENDLY_ERROR_SENTENCES, error)) return friendlyErrorT(locale, FRIENDLY_ERROR_SENTENCES[error])
  return documentsT(locale, fallback)
}

/** useEncryptedUpload's download / rename / delete line: its time-out sentence, else the general
 *  line. A storage, database or crypto message is never shown. */
export function documentsErrorText(error: string, locale: Locale): string {
  return sentenceText(error, locale, DOCUMENT_SENTENCES, 'docFailed')
}

/** useEncryptedUpload's upload line: its time-out sentence, else "Your document was not uploaded". */
export function uploadErrorText(error: string, locale: Locale): string {
  return sentenceText(error, locale, DOCUMENT_SENTENCES, 'uploadFailedBody')
}

/** The vault context's line: a wrong password or a time-out, else the general line of the mode. */
export function vaultErrorText(error: string, mode: 'setup' | 'unlock', locale: Locale): string {
  return sentenceText(error, locale, VAULT_SENTENCES, mode === 'setup' ? 'setupFailed' : 'vaultFailed')
}
