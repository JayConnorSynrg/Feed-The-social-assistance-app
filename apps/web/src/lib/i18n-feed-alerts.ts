export function alertsT(locale: Locale, key: keyof AlertMessages): string {
  return translate(alertMessages, locale, key)
}

const TYPE_KEYS: Record<AlertType, keyof AlertMessages> = {
  weather: 'typeWeather',
  road_closure: 'typeRoadClosure',
  speeding: 'typeSpeeding',
  general: 'typeGeneral',
}
const SEVERITY_KEYS: Record<number, keyof AlertMessages> = { 1: 'sevLow', 2: 'sevModerate', 3: 'sevHigh', 4: 'sevCritical' }
const SEVERITY_HINT_KEYS: Record<number, keyof AlertMessages> = { 1: 'sevLowHint', 2: 'sevModerateHint', 3: 'sevHighHint', 4: 'sevCriticalHint' }

/** The four severity levels, lowest first. */
export const ALERT_SEVERITIES = [1, 2, 3, 4] as const

/** "Road Closure" — an unknown type reads as the general one. */
export function alertTypeLabel(type: string, locale: Locale): string {
  return alertsT(locale, TYPE_KEYS[type as AlertType] ?? 'typeGeneral')
}

/** "High" — a level outside 1–4 reads as its number. */
export function alertSeverityLabel(severity: number, locale: Locale): string {
  const key = SEVERITY_KEYS[severity]
  return key ? alertsT(locale, key) : String(severity)
}

/** "High — significant risk" (the forms' severity options). */
export function alertSeverityHint(severity: number, locale: Locale): string {
  const key = SEVERITY_HINT_KEYS[severity]
  return key ? alertsT(locale, key) : String(severity)
}

/** A marker's or a link's name for an alert: "Road Closure, High". */
export function alertName(alert: { alert_type: string; severity: number }, locale: Locale): string {
  return formatMessage(alertsT(locale, 'typeAndSeverity'), {
    type: alertTypeLabel(alert.alert_type, locale),
    severity: alertSeverityLabel(alert.severity, locale),
  })
}

/** "Updated 5 minutes ago". relativeAge writes its age as the start of a sentence ("Hace 5 minutos");
 *  here it sits inside one, so its first letter is lower-cased in the viewer's language. */
export function alertUpdatedText(updatedAt: string, locale: Locale, now: number, tz?: string): string {
  const age = relativeAge(updatedAt, locale, now, tz)
  return formatMessage(alertsT(locale, 'updatedAgo'), { age: age.charAt(0).toLocaleLowerCase(localeTags(locale)) + age.slice(1) })
}

/** The sentence a refused alert action shows (never the server's text). */
export function alertFailureText(locale: Locale, failure: AlertRpcFailure): string {
  switch (failure.kind) {
    case 'guest':
      return alertsT(locale, 'failGuest')
    case 'forbidden':
      return alertsT(locale, 'failNotOwner')
    case 'invalid':
      return alertsT(locale, 'failInvalid')
    case 'network':
      return alertsT(locale, 'failNetwork')
    case 'not_live':
      return alertsT(locale, failure.resolved ? 'nowResolvedNotice' : 'notLiveNotice')
    case 'not_found':
      return alertsT(locale, 'notLiveNotice')
    case 'conflict':
    case 'unknown':
      return alertsT(locale, 'failUnknown')
  }
}

const EVENT_KEYS: Record<StripEvent['kind'], keyof AlertMessages> = {
  new: 'annNew',
  raised: 'annRaised',
  updated: 'annUpdated',
  resolved: 'annResolved',
  ended: 'annEnded',
}

/** One live-region sentence for a change on the strip. */
export function stripEventText(locale: Locale, event: StripEvent): string {
  return formatMessage(alertsT(locale, EVENT_KEYS[event.kind]), {
    type: alertTypeLabel(event.alert_type, locale),
    severity: alertSeverityLabel(event.severity, locale),
  })
}
