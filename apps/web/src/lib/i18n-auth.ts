// ---------------------------------------------------------------------------
// Failure codes → the line a member reads. The code is Supabase's AuthError.code (or the error's
// class, lib/failure-code.ts); an unknown code reads the page's general line.
// ---------------------------------------------------------------------------

const COMMON_FAILURES: Record<string, AuthKey> = {
  captcha_failed: 'captchaFailed',
  email_address_invalid: 'emailInvalid',
  validation_failed: 'emailInvalid',
  over_email_send_rate_limit: 'emailRateLimited',
}

function failureKey(code: string, own: Record<string, AuthKey>, fallback: AuthKey): AuthKey {
  if (Object.prototype.hasOwnProperty.call(own, code)) return own[code]
  if (Object.prototype.hasOwnProperty.call(COMMON_FAILURES, code)) return COMMON_FAILURES[code]
  return fallback
}

/** Sign in with email and password. */
export function signInFailureKey(code: string): AuthKey {
  return failureKey(code, {
    invalid_credentials: 'invalidCredentials',
    email_not_confirmed: 'emailNotConfirmed',
    over_request_rate_limit: 'loginRateLimited',
  }, 'signInFailed')
}

/** Sign up (and the confirmation email's resend: fallback resendFailed). */
export function signUpFailureKey(code: string, fallback: AuthKey = 'signupFailed'): AuthKey {
  return failureKey(code, {
    user_already_exists: 'accountExists',
    email_exists: 'accountExists',
    weak_password: 'passwordTooWeak',
    signup_disabled: 'signupUnavailable',
    email_provider_disabled: 'signupUnavailable',
    over_request_rate_limit: 'signupRateLimited',
  }, fallback)
}

/** Forgot password (fallback forgotFailed) and the new-password form (fallback resetFailed). */
export function passwordFailureKey(code: string, fallback: 'forgotFailed' | 'resetFailed'): AuthKey {
  return failureKey(code, {
    same_password: 'samePassword',
    weak_password: 'passwordTooWeak',
    over_request_rate_limit: 'emailRateLimited',
  }, fallback)
}

/** The /auth/callback and /auth/confirm `error` codes → their line; unknown → oauthFailed. */
export function oauthErrorKey(code: string): AuthKey {
  const keys: Record<string, AuthKey> = {
    oauth_provider: 'oauthProvider',
    exchange_failed: 'oauthExchange',
    no_code: 'oauthNoCode',
    no_session: 'oauthNoSession',
    confirmation_failed: 'confirmationFailed',
  }
  return Object.prototype.hasOwnProperty.call(keys, code) ? keys[code] : 'oauthFailed'
}

/** usePasswordStrength's `strength` code → its word. */
export function strengthKey(strength: 'weak' | 'fair' | 'good' | 'strong'): AuthKey {
  return ({ weak: 'strengthWeak', fair: 'strengthFair', good: 'strengthGood', strong: 'strengthStrong' } as const)[strength]
}

/** lib/security.ts validatePasswordStrength's hints (fixed English sentences) read as codes. */
const PASSWORD_FEEDBACK: Record<string, AuthKey> = {
  'Password must be at least 12 characters': 'pwMinLength',
  'Add lowercase letters': 'pwLowercase',
  'Add uppercase letters': 'pwUppercase',
  'Add numbers': 'pwNumbers',
  'Add special characters (!@#$%^&*)': 'pwSpecial',
  'Avoid common password patterns': 'pwCommon',
}

/** A password hint's key, or null for a sentence this table does not know (it is then not shown). */
export function passwordFeedbackKey(sentence: string): AuthKey | null {
  return Object.prototype.hasOwnProperty.call(PASSWORD_FEEDBACK, sentence) ? PASSWORD_FEEDBACK[sentence] : null
}
