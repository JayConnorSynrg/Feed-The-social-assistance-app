/** Looks up an event-form string with the shared EN fallback. */
export function eventFormT(locale: Locale, key: keyof EventFormMessages): string {
  return translate(eventFormMessages, locale, key)
}

/** Fills {name} placeholders (same rule as i18n-org-forms' formatMessage; kept here so member
 *  surfaces do not pull the org-forms dictionary into their bundle). */
export function formatMessage(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  )
}

/** The five event types of assistance_events.event_type (CHECK constraint), in display order. */
export const EVENT_TYPES = ['distribution', 'meal', 'pantry', 'clinic', 'other'] as const
export type EventType = (typeof EVENT_TYPES)[number]

const EVENT_TYPE_KEYS: Record<EventType, keyof EventFormMessages> = {
  distribution: 'typeDistribution',
  meal: 'typeMeal',
  pantry: 'typePantry',
  clinic: 'typeClinic',
  other: 'typeOther',
}

/** One badge colour set for every surface that shows an event type. */
export const EVENT_TYPE_COLORS: Record<EventType, string> = {
  distribution: 'bg-lime-100 text-lime-800',
  meal: 'bg-orange-100 text-orange-800',
  pantry: 'bg-amber-100 text-amber-800',
  clinic: 'bg-sky-100 text-sky-800',
  other: 'bg-stone-100 text-stone-700',
}

function isEventType(v: string): v is EventType {
  return (EVENT_TYPES as readonly string[]).includes(v)
}

/** Translated label of an event type; an unknown stored value is shown as-is. */
export function eventTypeLabel(type: string, locale: Locale): string {
  return isEventType(type) ? eventFormT(locale, EVENT_TYPE_KEYS[type]) : type
}

/** Badge classes of an event type ('other' for an unknown value). */
export function eventTypeColor(type: string): string {
  return isEventType(type) ? EVENT_TYPE_COLORS[type] : EVENT_TYPE_COLORS.other
}

const CHECKIN_KEYS: Record<string, keyof EventFormMessages> = {
  cancelled: 'checkinCancelled',
  anonymous: 'checkinAnonymous',
  attended: 'checkinAttended',
  checked_early: 'checkinCheckedEarly',
  ended: 'checkinEnded',
  in_window: 'checkinHere',
  early: 'checkinEarly',
}

/** The member's check-in button text (lib/event-checkin.ts computeCheckinButton kind) in their locale. */
export function checkinButtonLabel(kind: string, fallback: string, locale: Locale): string {
  const key = CHECKIN_KEYS[kind]
  return key ? eventFormT(locale, key) : fallback
}
