/** The English sentences lib/friendly-error.ts and the hooks write, read as codes. */
const PROGRAMS_SENTENCES: Record<string, ProgramsKey> = {
  'Programs timed out. Please try again.': 'programsTimeout',
  'Failed to load programs. Please try again.': 'programsLoadFailed',
}
const SAVED_SENTENCES: Record<string, ProgramsKey> = {
  'Saved resources timed out. Please try again.': 'savedTimeout',
  'Must be authenticated to save resources': 'signInToSave',
  'Must be authenticated to remove resources': 'signInToSave',
}

function sentenceText(error: string, locale: Locale, own: Record<string, ProgramsKey>, fallback: ProgramsKey): string {
  if (Object.prototype.hasOwnProperty.call(own, error)) return programsT(locale, own[error])
  if (Object.prototype.hasOwnProperty.call(FRIENDLY_ERROR_SENTENCES, error)) return friendlyErrorT(locale, FRIENDLY_ERROR_SENTENCES[error])
  return programsT(locale, fallback)
}

/** useProgramBrowser's error line in the viewer's language; text FEED did not write is never shown. */
export function programsErrorText(error: string, locale: Locale): string {
  return sentenceText(error, locale, PROGRAMS_SENTENCES, 'programsLoadFailed')
}

/** useSavedResources' error line; a raw database message becomes the general saved-programs line. */
export function savedErrorText(error: string, locale: Locale): string {
  return sentenceText(error, locale, SAVED_SENTENCES, 'savedFailed')
}

/** useResourceSearch's error: its timeout sentence, else the general search line. */
export function searchErrorText(error: Error, locale: Locale): string {
  return programsT(locale, error.message === 'Search timed out. Please try again.' ? 'searchTimeout' : 'searchFailed')
}

