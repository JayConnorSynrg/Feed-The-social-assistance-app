/** "<visible label>: <name>" — an accessible name that starts with the words on screen (WCAG 2.5.3)
 *  and then names the row it acts on; the name is isolated (it may run right to left). */
export function namedControl(label: string, name: string): string {
  return `${label}: ${isolate(name)}`
}
