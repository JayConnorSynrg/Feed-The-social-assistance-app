// ---------------------------------------------------------------------------
// Opening hours (business and organization pages)
// ---------------------------------------------------------------------------

const MINUTES_PER_DAY = 1440
// 2026-01-04 is a Sunday: day_of_week 0 … 6 is that date plus the day, read in UTC.
const SUNDAY_UTC = Date.UTC(2026, 0, 4)

/** A wall-clock minute of the day ("9:00 AM", "09:00", "오전 9:00") in the locale's own form. */
export function clockText(minuteOfDay: number, locale: Locale): string {
  const mod = ((minuteOfDay % MINUTES_PER_DAY) + MINUTES_PER_DAY) % MINUTES_PER_DAY
  return dateTimeFormatter(locale, 'UTC', { hour: 'numeric', minute: '2-digit' })
    .format(SUNDAY_UTC + mod * 60_000)
    .replace(/[\u00a0\u202f]/g, ' ')
}

/** A day_of_week (0 = Sunday) as the locale's short weekday name. */
export function weekdayShortText(day: number, locale: Locale): string {
  return dateTimeFormatter(locale, 'UTC', { weekday: 'short' }).format(SUNDAY_UTC + day * MINUTES_PER_DAY * 60_000)
}

/**
 * One business_hours row as an interval ("9:00 AM – 5:00 PM"). 00:00–24:00 is open24h; an interval
 * that closes at or before it opens ends the next day and says so; a zero-length or unparseable
 * row is null (omitted rather than shown broken).
 */
export function hoursIntervalText(row: BusinessHours, locale: Locale): string | null {
  const open = timeToMinutes(row.open_time)
  const close = timeToMinutes(row.close_time)
  if (open === null || close === null) return null
  if (open === 0 && close === MINUTES_PER_DAY) return shareT(locale, 'open24h')
  if (close === open) return null
  const hours = `${clockText(open, locale)} – ${clockText(close, locale)}`
  return close <= open ? formatMessage(shareT(locale, 'nextDay'), { hours }) : hours
}

/** The open-now pill's line ("Open now · closes 5:00 PM"); null when there are no usable hours. */
export function openNowText(state: OpenNowState, locale: Locale): string | null {
  if (!state) return null
  if (state.open && state.always) return shareT(locale, 'open24h')
  if (state.open) return formatMessage(shareT(locale, 'openNowCloses'), { time: clockText(state.closeMinute, locale) })
  return formatMessage(shareT(locale, 'closedOpens'), {
    day: weekdayShortText(state.openDay, locale),
    time: clockText(state.openMinute, locale),
  })
}
