// The public share pages (app/(social)/s/post, embed, business, organization, resource, donate and
// the (social) layout) in the 14 FEED locales: FEED's own words on each page and in its title /
// description metadata, plus the opening-hours lines of a business or organization. The page's
// language is the request's (lib/request-locale-server.ts: the feed_locale cookie, else
// Accept-Language — the one rule the root layout uses). Look up with shareT(locale, key) (English
// fallback, logged as i18n.translation_fallback).
// Words FEED already says elsewhere come from their one source: business categories and features
// and the Hours / Photos / Services / Closed words (lib/i18n-feed-businesses.ts), org types
// (lib/i18n-org-forms.ts via orgTypeKey), resource categories (lib/i18n-resource-categories.ts),
// the admin role marker (roleLabel, lib/i18n-feed-card.ts), petition signature counts
// (lib/i18n-feed-petitions.ts) and spots left / Full (lib/i18n-feed-optins.ts).
// Not here, on purpose: what members wrote (names, posts, descriptions — shown as written, marked
// lang="" or the post's own language, dir="auto"); the preview pictures and their descriptions
// (lib/og-card-labels.mjs — the picture's words are English); the oEmbed response, which is shared
// by a public cache and stays English (app/api/oembed/route.ts).
// Parity: i18n-share.test.ts.
// ht, so, am and hmn are machine-drafted, needs native review: docs/i18n-native-review.md.

