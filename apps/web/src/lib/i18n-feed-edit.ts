export function editT(locale: Locale, key: keyof EditMessages): string {
  return translate(editMessages, locale, key)
}

/** The edit dialog's title for a post type (petitions are not edited from the feed). */
export function editTitleKey(postType: PostType): keyof EditMessages {
  switch (postType) {
    case 'seeker_request':
      return 'editTitleRequest'
    case 'source_offer':
      return 'editTitleOffer'
    case 'event_post':
      return 'editTitleEvent'
    case 'poll':
      return 'editTitlePoll'
    case 'resource_post':
      return 'editTitleNote'
    default:
      return 'editTitlePost'
  }
}

/** A field's own validation message (the form shows it under the field, linked by aria-describedby). */
export function fieldErrorText(locale: Locale, error: FieldError): string {
  switch (error.code) {
    case 'required':
      return editT(locale, 'errRequired')
    case 'too_long':
      return formatMessage(editT(locale, 'errTooLong'), { max: error.max })
    case 'too_short':
      return formatMessage(editT(locale, 'errTooShort'), { min: error.min })
    case 'too_many':
      return formatMessage(editT(locale, 'errTooMany'), { max: error.max })
    case 'invalid':
      return editT(locale, 'errInvalid')
    case 'end_before_start':
      return editT(locale, 'errEndBeforeStart')
    case 'zone_required':
      return editT(locale, 'errZoneRequired')
    case 'zone_unsupported':
      return editT(locale, 'errZoneUnsupported')
    case 'capacity_range':
      return formatMessage(editT(locale, 'errCapacityRange'), { min: error.min, max: error.max })
    case 'options_count':
      return formatMessage(editT(locale, 'errOptionsCount'), { min: error.min, max: error.max })
    case 'options_duplicate':
      return editT(locale, 'errOptionsDuplicate')
    case 'option_empty':
      return editT(locale, 'errOptionEmpty')
    case 'poll_end_past':
      return editT(locale, 'errPollEndPast')
    case 'poll_end_shorten':
      return editT(locale, 'errPollEndShorten')
  }
}

/** A server refusal (lib/post-rpc.ts parsePostRpcError) as one message in the member's language. */
export function failureText(locale: Locale, failure: PostRpcFailure): string {
  switch (failure.kind) {
    case 'conflict':
      return editT(locale, 'failConflict')
    case 'not_found':
      return editT(locale, failure.token.startsWith('comment') ? 'failCommentGone' : 'failGone')
    case 'forbidden':
      switch (failure.token) {
        case 'not_author':
          return editT(locale, 'failNotAuthor')
        case 'post_removed':
          return editT(locale, 'failRemoved')
        case 'closed':
        case 'comments_closed':
        case 'comment_hidden':
          return editT(locale, 'failClosed')
        case 'guest_refused':
        case 'not_authenticated':
          return editT(locale, 'failGuest')
        default:
          return editT(locale, 'failPermission')
      }
    case 'locked':
      return editT(locale, 'failLocked')
    case 'capacity':
      return formatMessage(editT(locale, 'failCapacity'), { n: failure.committed ?? 0 })
    case 'event':
      return editT(locale, 'failEvent')
    case 'invalid':
      if (failure.field === 'resource_id') return editT(locale, 'failResource')
      if (failure.field === 'image_url') return editT(locale, 'failImage')
      return editT(locale, 'failInvalid')
    case 'required':
      return editT(locale, failure.field === 'reason' ? 'failReasonRequired' : 'failInvalid')
    case 'network':
      return editT(locale, 'failNetwork')
    case 'unknown':
      return editT(locale, 'failGeneric')
  }
}

/** A field's label (the same label the form shows; used by the conflict comparison). */
export function fieldLabel(locale: Locale, postType: PostType, field: EditField): string {
  switch (field) {
    case 'content':
      switch (postType) {
        case 'seeker_request':
          return composerT(locale, 'fieldRequest')
        case 'source_offer':
          return composerT(locale, 'fieldOffer')
        case 'event_post':
          return composerT(locale, 'fieldEventTitle')
        case 'poll':
          return composerT(locale, 'fieldPollQuestion')
        case 'resource_post':
          return composerT(locale, 'fieldResourceNote')
        default:
          return composerT(locale, 'fieldUpdate')
      }
    case 'image_url':
      return editT(locale, 'labelPhoto')
    case 'image_alt':
      return editT(locale, 'fieldImageAlt')
    case 'max_seekers':
      return composerT(locale, 'fieldCapacity')
    case 'categories':
      return composerT(locale, 'fieldCategories')
    case 'starts_at':
      return composerT(locale, 'fieldStartsAt')
    case 'ends_at':
      return composerT(locale, postType === 'poll' ? 'fieldPollEnds' : 'fieldEndsAt')
    case 'time_zone':
      return composerT(locale, 'fieldTimeZone')
    case 'is_online':
      return composerT(locale, 'fieldOnline')
    case 'location':
      return composerT(locale, 'fieldLocation')
    case 'options':
      return composerT(locale, 'fieldOptions')
  }
}

/** A post_revisions.fields_changed entry as a label ('metadata' / 'poll' are the server's own names). */
export function historyFieldLabel(locale: Locale, postType: PostType | 'comment', field: string): string {
  if (postType === 'comment') return composerT(locale, 'fieldUpdate')
  if (field === 'metadata') return editT(locale, 'labelDetails')
  if (field === 'poll') return editT(locale, 'labelPollSettings')
  const known: readonly string[] = ['content', 'image_url', 'image_alt', 'max_seekers']
  return known.includes(field) ? fieldLabel(locale, postType, field as EditField) : editT(locale, 'labelDetails')
}

/** Who removed private details from a version — a role, never a name. */
export function redactorText(locale: Locale, role: string): string {
  return editT(locale, role === 'platform_admin' ? 'redactedByAdmin' : 'redactedByAuthor')
}
