// Stored values stay as stored (lib/business-vocab.ts): organizations.business_category,
// cost_model and the attributes keys each get their label from one function here
// (businessCategoryLabel, costModelLabel, businessAttributeLabel). Weekday names come from
// weekdayName (lib/event-recurrence-format.ts) and the distance from distanceBucketLabel.
//
// The panel's own three failure fallbacks are codes (BUSINESS_LOAD_FAILED, …); businessFailure()
// turns a code into the member's sentence. Any other failure text comes from the server or from
// lib/business-data.ts, is English, and is returned flagged so the panel marks it English.
// Parity: i18n-feed-subtabs.test.ts.
// ht, so, am and hmn are machine-drafted, needs native review: docs/i18n-native-review.md.

