/** The panel's own fallbacks, stored as codes and shown as sentences. */
export const BUSINESS_LOAD_FAILED = 'load_failed'
export const BUSINESS_UPLOAD_FAILED = 'upload_failed'
export const BUSINESS_SUBMIT_FAILED = 'submit_failed'

const FAILURE_KEYS: Record<string, keyof FeedBusinessesMessages> = {
  [BUSINESS_LOAD_FAILED]: 'loadFailed',
  [BUSINESS_UPLOAD_FAILED]: 'uploadFailed',
  [BUSINESS_SUBMIT_FAILED]: 'submitFailed',
}

/**
 * What a failure shows. One of the panel's codes reads in the viewer's language
 * (`translated: true`). Anything else came from the server or from lib/business-data.ts, is
 * English, and is returned as received with `translated: false` so the panel marks it
 * lang="en" dir="ltr".
 */
export function businessFailure(value: string, locale: Locale): { text: string; translated: boolean } {
  return Object.prototype.hasOwnProperty.call(FAILURE_KEYS, value)
    ? { text: businessesT(locale, FAILURE_KEYS[value]), translated: true }
    : { text: value, translated: false }
}
