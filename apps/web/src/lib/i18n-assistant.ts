export function assistantT(locale: Locale, key: AssistantKey): string {
  return translate(assistantMessages, locale, key)
}

/**
 * A guided flow's words: a dictionary key; a key with dollar amounts (formatted for the locale with
 * formatUsd, lib/i18n-intl.ts); or a literal that reads the same in every language (a digit).
 */
export type FlowText = AssistantKey | { key: AssistantKey; usd: Record<string, number> } | { literal: string }

export function flowText(locale: Locale, text: FlowText): string {
  if (typeof text === 'string') return assistantT(locale, text)
  if ('literal' in text) return text.literal
  const vars: Record<string, string> = {}
  for (const [name, amount] of Object.entries(text.usd)) vars[name] = formatUsd(amount, locale)
  return formatMessage(assistantT(locale, text.key), vars)
}
