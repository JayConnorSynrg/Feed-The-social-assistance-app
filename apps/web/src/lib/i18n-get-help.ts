/**
 * Where an option's words come from. The option's value is separate and never translated.
 *   getHelp   — this dictionary;
 *   assistant — a word lib/i18n-assistant.ts already says (`lang: 'en'` marks a US program name
 *               written the same in every language);
 *   state     — a state, by its English name (the option's value): usStateName of its code;
 *   usd*      — a dollar range in the Assistant's income-range words, amounts via formatUsd.
 */
export type WizardLabel =
  | { kind: 'getHelp'; key: GetHelpKey }
  | { kind: 'assistant'; key: AssistantKey; lang?: 'en' }
  | { kind: 'state'; name: string }
  | { kind: 'usdUnder' | 'usdOver'; amount: number }
  | { kind: 'usdRange'; from: number; to: number }

export function wizardLabelText(label: WizardLabel, locale: Locale): string {
  switch (label.kind) {
    case 'getHelp':
      return getHelpT(locale, label.key)
    case 'assistant':
      return assistantT(locale, label.key)
    case 'state':
      return usStateName(STATE_TO_ABBR[label.name] ?? label.name, locale)
    case 'usdUnder':
      return formatMessage(assistantT(locale, 'ecIncomeUnder'), { amount: formatUsd(label.amount, locale) })
    case 'usdOver':
      return formatMessage(assistantT(locale, 'ecIncomeOver'), { amount: formatUsd(label.amount, locale) })
    case 'usdRange':
      return formatMessage(assistantT(locale, 'ecIncomeRange'), { from: formatUsd(label.from, locale), to: formatUsd(label.to, locale) })
  }
}

/** A wizard category's name: the resource category of the same id (the Jobs wizard is `employment`). */
export function wizardCategoryLabel(id: string, locale: Locale): string {
  return resourceCategoryLabel(id === 'jobs' ? 'employment' : id, locale)
}
