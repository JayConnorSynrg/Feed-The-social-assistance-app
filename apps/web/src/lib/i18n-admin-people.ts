export interface AdminPeopleMessages {
  /** admin_list_people failed (logged as admin.people.list_failed with its code). */
  loadFailed: string
  /** Announced (role="status") after a tier change succeeded. */
  tierUpdated: string
  changeFailed: string
  /** An admin_set_tier refusal code this dictionary has no sentence for; {code} is that code. */
  deniedCode: string
  denySelf: string
  denyFounderOnly: string
  denyInsufficientTier: string
  denyNoChange: string
  denyTargetInvalid: string
  denyAuth: string
  /** The search box: its visible label and accessible name. */
  searchLabel: string
  search: string
  loading: string
  empty: string
  colPerson: string
  colTier: string
  colSetTier: string
  noName: string
  noActions: string
  /** Accessible name of a row's tier select: starts with colSetTier, then {name}, the person's own name. */
  setTierFor: string
  change: string
  /** A grant option; {tier} is roleLabel(tier). */
  makeTier: string
  revokeTier: string
  /** {tier} and {name} are rendered as their own bold elements (the name with its own direction). */
  grantTo: string
  /** {name} is rendered as its own bold element with its own direction. */
  revokeFrom: string
  reasonRequired: string
  /** Stands in for {name} when the person has neither a first name nor a username. */
  thisPerson: string
  /** The reason box: its visible label and accessible name. */
  reasonLabel: string
  cancel: string
  apply: string
  applying: string
  /** Accessible name of the dialog's close button. */
  close: string
}

