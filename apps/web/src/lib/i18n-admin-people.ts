export function adminPeopleT(locale: Locale, key: keyof AdminPeopleMessages): string {
  return translate(adminPeopleMessages, locale, key)
}

/** admin_set_tier's refusal codes ({ok:false, code}). */
const DENIAL_KEY: Record<string, keyof AdminPeopleMessages> = {
  self: 'denySelf',
  founder_only: 'denyFounderOnly',
  insufficient_tier: 'denyInsufficientTier',
  no_change: 'denyNoChange',
  target_invalid: 'denyTargetInvalid',
  auth: 'denyAuth',
}

/** The sentence for an admin_set_tier refusal; an unknown code is named as it is. */
export function denialText(code: string, locale: Locale): string {
  const key = Object.prototype.hasOwnProperty.call(DENIAL_KEY, code) ? DENIAL_KEY[code] : null
  return key ? adminPeopleT(locale, key) : formatMessage(adminPeopleT(locale, 'deniedCode'), { code })
}

/** A tier option ("Make Moderator" / "Revoke tier"), the tier named by roleLabel. */
export function grantOptionLabel(option: GrantOption, locale: Locale): string {
  return option.value
    ? formatMessage(adminPeopleT(locale, 'makeTier'), { tier: roleLabel(option.value, locale) })
    : adminPeopleT(locale, 'revokeTier')
}
