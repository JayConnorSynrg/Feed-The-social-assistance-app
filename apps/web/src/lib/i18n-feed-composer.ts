export function composerT(locale: Locale, key: keyof ComposerMessages): string {
  return translate(composerMessages, locale, key)
}

/** The request / offer categories a member can pick (the stored values, in chip order). */
export const REQUEST_CATEGORIES = ['Food', 'Housing', 'Goods', 'Transit', 'Health', 'Money', 'Care', 'Education', 'Work', 'Legal'] as const

const CATEGORY_KEY: Record<(typeof REQUEST_CATEGORIES)[number], keyof ComposerMessages> = {
  Food: 'catFood',
  Housing: 'catHousing',
  Goods: 'catGoods',
  Transit: 'catTransit',
  Health: 'catHealth',
  Money: 'catMoney',
  Care: 'catCare',
  Education: 'catEducation',
  Work: 'catWork',
  Legal: 'catLegal',
}

/** A stored request / offer category as its label in the viewer's language (unknown values as stored). */
export function requestCategoryLabel(category: string, locale: Locale): string {
  const key = CATEGORY_KEY[category as (typeof REQUEST_CATEGORIES)[number]]
  return key ? composerT(locale, key) : category
}
