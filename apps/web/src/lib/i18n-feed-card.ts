export function cardT(locale: Locale, key: keyof CardMessages): string {
  return translate(cardMessages, locale, key)
}

/** The public tier marker of an author (never read from profile display columns). */
export function roleLabel(tier: AdminTier | null, locale: Locale): string {
  switch (tier) {
    case 'community_moderator':
      return cardT(locale, 'roleModerator')
    case 'resource_admin':
      return cardT(locale, 'roleResourceAdmin')
    case 'platform_admin':
      return cardT(locale, 'roleAdmin')
    default:
      return cardT(locale, 'roleMember')
  }
}

