type SanitizedEvent =
  | { ok: true; context: Record<string, string | number | boolean | null> }
  | { ok: false; reason: 'unknown_event' }

/**
 * Filter one event against the registry (used by /api/client-log AND the server sink). Unknown event -> rejected.
 * Known event -> only its registered label keys survive, values must be flat
 * primitives (strings capped at 200 chars), and the standard error fields are kept
 * only when `level` is 'error' (error_message capped at MAX_ERROR_MESSAGE_LEN).
 */
export function sanitizeClientEvent(
  event: string,
  level: 'info' | 'warn' | 'error',
  context: unknown
): SanitizedEvent {
  if (!Object.prototype.hasOwnProperty.call(EVENT_REGISTRY, event)) {
    return { ok: false, reason: 'unknown_event' }
  }
  const allowed = new Set<string>(EVENT_REGISTRY[event])
  if (level === 'error') ERROR_LABEL_KEYS.forEach((k) => allowed.add(k))

  const out: Record<string, string | number | boolean | null> = {}
  if (context && typeof context === 'object' && !Array.isArray(context)) {
    for (const [key, value] of Object.entries(context as Record<string, unknown>)) {
      if (!allowed.has(key)) continue
      if (typeof value === 'string') {
        out[key] = value.slice(0, key === 'error_message' ? MAX_ERROR_MESSAGE_LEN : 200)
      } else if (typeof value === 'number') {
        if (Number.isFinite(value)) out[key] = value
      } else if (typeof value === 'boolean' || value === null) {
        out[key] = value
      }
    }
  }
  return { ok: true, context: out }
}
