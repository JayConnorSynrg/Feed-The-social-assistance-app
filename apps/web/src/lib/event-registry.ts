// apps/web/src/lib/event-registry.ts
//
// Closed vocabulary for first-party telemetry. FEED keeps its logs on its own
// infrastructure (the Supabase `app_logs` table); this registry is the contract
// for what a browser may write there through /api/client-log.
//
//   event name -> the label keys that event may carry
//
// The route rejects an event name that is not a key here, drops any label key
// not listed for that event, and keeps the standard error fields
// (ERROR_LABEL_KEYS) only on error-level rows, with error_message capped at
// MAX_ERROR_MESSAGE_LEN characters.
//
// Sourcing: every event name the app emits — the static name argument of every
// logger.debug/info/warn/error, withMetric (as `<op>.complete` / `<op>.error`),
// privilegedRpc / privilegedFetch op and logEvent call in apps/web/src — plus
// every DISTINCT event seen in production app_logs over the trailing 30 days.
// Label keys come from the same call sites plus the production context keys,
// minus free-text and personal fields (user ids, emails, addresses, viewport
// bounds, file paths, raw query text, raw error text outside error_message).
// Events whose subject is a person (admin.user.*, admin.tier.set*, admin.notes.*,
// admin.denied, admin.audit.*) carry no target_id: their request_id joins to the
// durable admin_actions row, which already records the target.
// src/lib/__tests__/event-registry.test.ts re-scans the source on every run and
// fails when an emitted event is missing from this list.
//
// Adding an event: add `'<name>': ['label', ...]` here in the same PR that first
// emits it.

