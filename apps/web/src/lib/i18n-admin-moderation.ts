export function adminModerationT(locale: Locale, key: keyof AdminModerationMessages): string {
  return translate(adminModerationMessages, locale, key)
}

/** "3 reports": the count in the locale's digits, in the plural form the locale gives it. */
export function moderationCount(table: Record<Locale, PluralForms>, n: number, locale: Locale): string {
  return formatMessage(pluralMessage(table[locale] ?? table.en, n, locale), { n: formatCount(n, locale) })
}

const ACTION_KEY = {
  remove: 'actionRemove',
  hold: 'actionHold',
  authorize: 'actionAuthorize',
} as const satisfies Record<PostModerationAction, keyof AdminModerationMessages>

const DONE_KEY = {
  remove: 'doneRemove',
  hold: 'doneHold',
  authorize: 'doneAuthorize',
} as const satisfies Record<PostModerationAction, keyof AdminModerationMessages>

/** A post moderation button's label — the same words in the reports queue and the linked post. */
export function moderationActionLabel(action: PostModerationAction, locale: Locale): string {
  return adminModerationT(locale, ACTION_KEY[action])
}

/** The line the linked post's status region announces after an action succeeded. */
export function moderationActionDone(action: PostModerationAction, locale: Locale): string {
  return adminModerationT(locale, DONE_KEY[action])
}
